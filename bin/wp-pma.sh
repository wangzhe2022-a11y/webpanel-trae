#!/bin/bash
# ============================================================================
# wp-pma.sh - built-in phpMyAdmin (root only via sudo)
#
#   status       install state + version (json)
#   install      download official tarball, write config, MySQL user, nginx/fpm
#   uninstall    remove phpMyAdmin files, FPM pool, dedicated MySQL user
#
# phpMyAdmin is served on the panel vhost at /phpmyadmin/ (HTTPS :8888),
# gated by the panel session (nginx auth_request → /phpmyadmin-auth).
# It is NOT exposed as a public site and does not require Installatron.
#
# Secrets (blowfish_secret, dedicated MySQL password) are generated at
# install time under /www/server/phpmyadmin/ and never committed.
# ============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=wp-lib.sh
. "$SCRIPT_DIR/wp-lib.sh"
set -o pipefail

PMA_VERSION="${PMA_VERSION:-5.2.3}"
PMA_TARBALL="phpMyAdmin-${PMA_VERSION}-all-languages.tar.gz"
PMA_URL="${PMA_URL:-https://files.phpmyadmin.net/phpMyAdmin/${PMA_VERSION}/${PMA_TARBALL}}"
# official SHA256 for 5.2.3-all-languages.tar.gz (files.phpmyadmin.net)
PMA_SHA256="${PMA_SHA256:-12ba1c425fa4071abbd4e7668c9ebdeac0b0755a467a6d6d5026122bb47c102b}"
PMA_ROOT="${PMA_ROOT:-/www/server/phpmyadmin}"
PMA_USER="${PMA_USER:-webpanel_pma}"
PMA_FPM_CONF="${PMA_FPM_CONF:-/etc/php-fpm.d/phpmyadmin.conf}"
PMA_FPM_TPL="${PMA_FPM_TPL:-/usr/local/webpanel/config/php-fpm/phpmyadmin.conf}"
PMA_CFG_TPL="${PMA_CFG_TPL:-/usr/local/webpanel/config/phpmyadmin/config.inc.php}"
PMA_NGINX_INC="${PMA_NGINX_INC:-/usr/local/webpanel/config/nginx/phpmyadmin.inc}"
PMA_NGINX_LIVE="${PMA_NGINX_LIVE:-/etc/nginx/conf.d/00-webpanel.conf}"
SECRET_ENV="$PMA_ROOT/.wp-secret"
SECRET_PHP="$PMA_ROOT/config.secret.php"
DRY_MARKER="/tmp/wp-dry-pma-installed"

json_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

usage() { fail "usage: wp-pma.sh {status|install|uninstall}" 64; }
[ $# -ge 1 ] || usage
action="$1"; shift
require_root

pma_version_file() {
    if [ -f "$PMA_ROOT/.webpanel-version" ]; then
        cat "$PMA_ROOT/.webpanel-version"
    elif [ -f "$PMA_ROOT/index.php" ]; then
        printf 'unknown'
    fi
}

# ============================================================================
# status
# ============================================================================
cmd_status() {
    [ $# -eq 0 ] || usage
    if is_dry_run; then
        if [ -f "$DRY_MARKER" ]; then
            ok "\"installed\":true,\"version\":\"${PMA_VERSION}-dryrun\",\"url\":\"/phpmyadmin/\""
        fi
        ok "\"installed\":false,\"version\":\"\",\"url\":\"/phpmyadmin/\""
    fi
    if [ ! -f "$PMA_ROOT/index.php" ]; then
        ok "\"installed\":false,\"version\":\"\",\"url\":\"/phpmyadmin/\""
    fi
    local ver
    ver="$(pma_version_file)"
    ok "\"installed\":true,\"version\":\"$(json_escape "$ver")\",\"url\":\"/phpmyadmin/\""
}

rand_alnum() {
    local n="$1" bytes s
    bytes=$(( (n + 1) / 2 ))
    s="$(openssl rand -hex "$bytes" 2>/dev/null || true)"
    s="${s:0:$n}"
    [ ${#s} -eq "$n" ] || fail "failed to generate random secret"
    printf '%s' "$s"
}

php_escape() {
    # single-quoted PHP string; secrets are alphanumeric so this is belt-and-suspenders
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\'/\\\'}"
    printf '%s' "$s"
}

write_secret_php() {
    local bf="$1" pw="$2"
    cat > "$SECRET_PHP" <<EOF
<?php
// generated by WebPanel wp-pma.sh — do not commit
\$cfg['blowfish_secret'] = '$(php_escape "$bf")';
\$cfg['Servers'][1]['user'] = '$(php_escape "$PMA_USER")';
\$cfg['Servers'][1]['password'] = '$(php_escape "$pw")';
EOF
    chown root:webpanel "$SECRET_PHP" 2>/dev/null || chown root:root "$SECRET_PHP"
    chmod 640 "$SECRET_PHP"
}

load_or_create_secrets() {
    local bf pw
    if [ -f "$SECRET_ENV" ]; then
        # shellcheck disable=SC1090
        . "$SECRET_ENV"
        bf="${BLOWFISH:-}"
        pw="${MYSQL_PASSWORD:-}"
        [ -n "$bf" ] && [ -n "$pw" ] || fail "phpMyAdmin secret file is incomplete"
        printf '%s %s' "$bf" "$pw"
        return 0
    fi
    bf="$(rand_alnum 64)"
    pw="$(rand_alnum 28)"
    umask 077
    mkdir -p "$PMA_ROOT"
    cat > "$SECRET_ENV" <<EOF
BLOWFISH=$bf
MYSQL_USER=$PMA_USER
MYSQL_PASSWORD=$pw
EOF
    chmod 600 "$SECRET_ENV"
    printf '%s %s' "$bf" "$pw"
}

ensure_mysql_user() {
    local pw="$1"
    mysql_cmd <<SQL || fail "failed to create phpMyAdmin MySQL user (is mysqld running?)"
CREATE USER IF NOT EXISTS '$PMA_USER'@'127.0.0.1' IDENTIFIED WITH caching_sha2_password BY '$pw';
ALTER USER '$PMA_USER'@'127.0.0.1' IDENTIFIED WITH caching_sha2_password BY '$pw';
CREATE USER IF NOT EXISTS '$PMA_USER'@'localhost' IDENTIFIED WITH caching_sha2_password BY '$pw';
ALTER USER '$PMA_USER'@'localhost' IDENTIFIED WITH caching_sha2_password BY '$pw';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, RELOAD, PROCESS,
      REFERENCES, INDEX, ALTER, SHOW DATABASES, CREATE TEMPORARY TABLES,
      LOCK TABLES, EXECUTE, REPLICATION CLIENT, CREATE VIEW, SHOW VIEW,
      CREATE ROUTINE, ALTER ROUTINE, EVENT, TRIGGER, CREATE USER
ON *.* TO '$PMA_USER'@'127.0.0.1';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, RELOAD, PROCESS,
      REFERENCES, INDEX, ALTER, SHOW DATABASES, CREATE TEMPORARY TABLES,
      LOCK TABLES, EXECUTE, REPLICATION CLIENT, CREATE VIEW, SHOW VIEW,
      CREATE ROUTINE, ALTER ROUTINE, EVENT, TRIGGER, CREATE USER
ON *.* TO '$PMA_USER'@'localhost';
FLUSH PRIVILEGES;
SQL
}

ensure_packages() {
    if command -v dnf >/dev/null 2>&1; then
        dnf install -y php-mysqlnd php-zip >/dev/null 2>&1 \
            || fail "failed to install php-mysqlnd / php-zip (required by phpMyAdmin)"
    fi
}

ensure_fpm_pool() {
    local tpl="$PMA_FPM_TPL"
    [ -f "$tpl" ] || tpl="$SCRIPT_DIR/../config/php-fpm/phpmyadmin.conf"
    [ -f "$tpl" ] || fail "phpMyAdmin FPM pool template missing"
    install -m 644 "$tpl" "$PMA_FPM_CONF"
}

ensure_nginx_include() {
    local inc="$PMA_NGINX_INC"
    [ -f "$inc" ] || inc="$SCRIPT_DIR/../config/nginx/phpmyadmin.inc"
    [ -f "$inc" ] || fail "phpMyAdmin nginx snippet missing: $inc"
    [ -f "$PMA_NGINX_LIVE" ] || fail "panel nginx config missing: $PMA_NGINX_LIVE"
    if grep -q 'phpmyadmin.inc' "$PMA_NGINX_LIVE"; then
        return 0
    fi
    local tmp
    tmp="$(mktemp)"
    awk -v inc="    include ${inc};" '
        { lines[NR] = $0 }
        END {
            last = 0
            for (i = NR; i >= 1; i--) {
                if (lines[i] ~ /^[[:space:]]*}[[:space:]]*$/) { last = i; break }
            }
            if (last == 0) last = NR
            for (i = 1; i <= NR; i++) {
                if (i == last) print inc
                print lines[i]
            }
        }
    ' "$PMA_NGINX_LIVE" > "$tmp" || fail "failed to patch panel nginx config"
    install -m 644 "$tmp" "$PMA_NGINX_LIVE"
    rm -f "$tmp"
}

download_and_extract() {
    local stage tgz sum
    # already at the pinned version? keep tree, refresh config only
    if [ -f "$PMA_ROOT/index.php" ] && [ "$(pma_version_file)" = "$PMA_VERSION" ]; then
        return 0
    fi
    stage="$(mktemp -d /tmp/webpanel-pma.XXXXXX)" || fail "无法创建临时目录"
    tgz="$stage/$PMA_TARBALL"
    curl -fsSL --retry 3 --retry-delay 2 -o "$tgz" "$PMA_URL" \
        || { rm -rf "$stage"; fail "下载 phpMyAdmin 失败（请检查服务器外网连接 files.phpmyadmin.net）"; }
    (
        cd "$stage" || exit 1
        printf '%s  %s\n' "$PMA_SHA256" "$PMA_TARBALL" | sha256sum -c >/dev/null
    ) || { rm -rf "$stage"; fail "phpMyAdmin 校验和不匹配，已中止安装"; }

    tar -xzf "$tgz" -C "$stage" || { rm -rf "$stage"; fail "phpMyAdmin 解压失败"; }
    local extracted
    extracted="$(find "$stage" -mindepth 1 -maxdepth 1 -type d -name 'phpMyAdmin-*' -print -quit)"
    [ -n "$extracted" ] && [ -f "$extracted/index.php" ] \
        || { rm -rf "$stage"; fail "phpMyAdmin 解压后未找到 index.php"; }

    # drop files that must not be web-reachable
    rm -rf "$extracted/setup" "$extracted/examples" "$extracted/composer.json" \
        "$extracted/composer.lock" "$extracted/CONTRIBUTING.md"

    # preserve secrets across upgrades
    local keep
    keep="$(mktemp -d /tmp/webpanel-pma-keep.XXXXXX)"
    [ -f "$SECRET_ENV" ] && cp -a "$SECRET_ENV" "$keep/" || true
    [ -f "$SECRET_PHP" ] && cp -a "$SECRET_PHP" "$keep/" || true

    rm -rf "$PMA_ROOT"
    mkdir -p "$(dirname "$PMA_ROOT")"
    mv "$extracted" "$PMA_ROOT"
    printf '%s\n' "$PMA_VERSION" > "$PMA_ROOT/.webpanel-version"
    [ -f "$keep/.wp-secret" ] && cp -a "$keep/.wp-secret" "$SECRET_ENV" || true
    [ -f "$keep/config.secret.php" ] && cp -a "$keep/config.secret.php" "$SECRET_PHP" || true
    rm -rf "$keep" "$stage"
}

harden_tree() {
    local tpl="$PMA_CFG_TPL"
    [ -f "$tpl" ] || tpl="$SCRIPT_DIR/../config/phpmyadmin/config.inc.php"
    [ -f "$tpl" ] || fail "phpMyAdmin config template missing"
    install -m 640 -o root -g webpanel "$tpl" "$PMA_ROOT/config.inc.php" 2>/dev/null \
        || install -m 640 "$tpl" "$PMA_ROOT/config.inc.php"

    install -d -o webpanel -g webpanel -m 700 "$PMA_ROOT/tmp"

    chown -R root:webpanel "$PMA_ROOT"
    # tmp must stay writable for the FPM user
    chown webpanel:webpanel "$PMA_ROOT/tmp"
    find "$PMA_ROOT" -type d -exec chmod 750 {} \;
    find "$PMA_ROOT" -type f -exec chmod 640 {} \;
    chmod 700 "$PMA_ROOT/tmp"
    chmod 600 "$SECRET_ENV" 2>/dev/null || true
    chmod 640 "$SECRET_PHP" 2>/dev/null || true
}

reload_services() {
    if [ -s /run/php-fpm/panel.sock ] || systemctl is-active --quiet php-fpm 2>/dev/null; then
        systemctl restart php-fpm || fail "php-fpm restart failed (phpMyAdmin pool)"
    fi
    if command -v nginx >/dev/null 2>&1 && [ -f "$PMA_NGINX_LIVE" ]; then
        nginx -t || fail "nginx config test failed after phpMyAdmin include"
        systemctl reload nginx >/dev/null 2>&1 || true
    fi
}

# ============================================================================
# install (idempotent)
# ============================================================================
cmd_install() {
    [ $# -eq 0 ] || usage
    if is_dry_run; then
        touch "$DRY_MARKER"
        ok "\"installed\":true,\"version\":\"${PMA_VERSION}-dryrun\",\"url\":\"/phpmyadmin/\""
    fi

    id webpanel >/dev/null 2>&1 || fail "webpanel 系统用户不存在"
    ensure_packages
    mkdir -p "$PMA_ROOT"
    chmod 750 "$PMA_ROOT"

    download_and_extract

    local secrets bf pw
    secrets="$(load_or_create_secrets)"
    bf="${secrets%% *}"
    pw="${secrets#* }"
    write_secret_php "$bf" "$pw"
    ensure_mysql_user "$pw"
    harden_tree
    ensure_fpm_pool
    ensure_nginx_include
    reload_services

    ok "\"installed\":true,\"version\":\"$(json_escape "$PMA_VERSION")\",\"url\":\"/phpmyadmin/\""
}

# ============================================================================
# uninstall
# ============================================================================
cmd_uninstall() {
    [ $# -eq 0 ] || usage
    if is_dry_run; then
        rm -f "$DRY_MARKER"
        ok
    fi
    rm -f "$PMA_FPM_CONF"
    if mysql_cmd -e "SELECT 1" >/dev/null 2>&1; then
        mysql_cmd -e "DROP USER IF EXISTS '$PMA_USER'@'127.0.0.1'; DROP USER IF EXISTS '$PMA_USER'@'localhost'; FLUSH PRIVILEGES;" \
            || true
    fi
    rm -rf "$PMA_ROOT"
    if systemctl is-active --quiet php-fpm 2>/dev/null; then
        systemctl restart php-fpm >/dev/null 2>&1 || true
    fi
    if command -v nginx >/dev/null 2>&1; then
        systemctl reload nginx >/dev/null 2>&1 || true
    fi
    ok
}

case "$action" in
    status)    cmd_status "$@" ;;
    install)   cmd_install "$@" ;;
    uninstall) cmd_uninstall "$@" ;;
    *) usage ;;
esac
